    static readonly string order;
    static Texture2D atlas;
    static bool loaded;

    static PixelFont() => order = new string(glyphs.Keys.ToArray());

    public static void Load()
    {
        var p = new Pix(order.Length * CW, CH);
        for (int i = 0; i < order.Length; i++) Paint(p, order[i], i * CW, 0, 1, new Color(255, 255, 255, 255));
        atlas = p.ToTexture();
        loaded = true;
    }

    public static void Unload() { if (loaded) Raylib.UnloadTexture(atlas); }

    static byte[] Glyph(char c) => glyphs.TryGetValue(char.ToUpperInvariant(c), out var g) ? g : glyphs['?'];

    static void Paint(Pix p, char c, int x, int y, int s, Color col)
    {
        var g = Glyph(c);
        for (int r = 0; r < GH; r++)
            for (int b = 0; b < GW; b++)
                if ((g[r] >> (GW - 1 - b) & 1) != 0)
                    p.Rect(x + b * s, y + r * s, s, s, col);
    }

    /// <summary>Size in virtual units at font scale s (canvas pixels per font pixel).</summary>
    public static Vector2 Measure(string text, int s) => new(MathF.Max(0, text.Length * CW - 1) * s / K.Px, GH * s / K.Px);

    public static void Draw(string text, Vector2 pos, int s, Color col)
    {
        float unit = s / K.Px;
        float x = MathF.Round(pos.X * K.Px) / K.Px, y = MathF.Round(pos.Y * K.Px) / K.Px;
        foreach (char ch in text)
        {
            int idx = order.IndexOf(char.ToUpperInvariant(ch));
            if (idx < 0) idx = order.IndexOf('?');
            if (ch != ' ')
                Raylib.DrawTexturePro(atlas, new Rectangle(idx * CW, 0, GW, GH), new Rectangle(x, y, GW * unit, GH * unit), Vector2.Zero, 0, col);
            x += CW * unit;
        }
    }

    /// <summary>CPU version for previews / baked art. Coordinates in pixels.</summary>
    public static void DrawPix(Pix p, string text, int x, int y, int s, Color col)
    {
        foreach (char ch in text) { Paint(p, ch, x, y, s, col); x += CW * s; }
    }

    public static int PixWidth(string text, int s) => Math.Max(0, text.Length * CW - 1) * s;
}
